import { readFile, writeFile } from "node:fs/promises";

// keep browser URLs separate so neither font binaries nor glyph metrics enter the public Worker.
const source = await readFile("src/assets/fallback-fonts.ts", "utf8");
const advancesStart = source.indexOf("const advances =");
const selectionStart = source.indexOf("export function fallbackFontsForText");
const metricsStart = source.indexOf("export function previewFontFamily");
const importsAndPages = source.slice(0, advancesStart);
const pageNames = [...importsAndPages.matchAll(/\[0x([a-f0-9]+), page/g)].map((match) => `0x${match[1]}`);
const metrics = `${source.slice(advancesStart, selectionStart)}\nconst cjkPages = new Set([${pageNames.join(",")}]);\n${source.slice(metricsStart)}`;
await writeFile("src/assets/preview-font-metrics.ts", `// generated by scripts/prepare-preview-fonts.ts.\n${metrics}`);
const urls = importsAndPages.replaceAll('.bin"', '.bin?url"').replaceAll("ArrayBuffer", "string")
  + source.slice(selectionStart, metricsStart).replaceAll("fallbackFontsForText", "fallbackFontUrlsForText")
    .replaceAll("ArrayBuffer", "string");
await writeFile("src/assets/preview-font-urls.ts", `// generated by scripts/prepare-preview-fonts.ts.\n${urls}`);
