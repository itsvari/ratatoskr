"""Regenerate committed fonts; normal builds do not require Python/fontTools.

Usage: python scripts/subset-preview-fonts.py /path/to/noto-sans-sc.ttf /path/to/noto-sans-arabic.ttf
Source revisions and licences are documented in src/assets/README.md.
"""
from collections import defaultdict
from io import BytesIO
from pathlib import Path
import sys
import subprocess

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

destination = Path("src/assets/fallbacks")
destination.mkdir(parents=True, exist_ok=True)


def rename(font, family):
    for identifier, value in [(1, family), (2, "Regular"), (4, family),
                              (6, family.replace(" ", "") + "-Regular"), (16, family), (17, "Regular")]:
        for record in list(font["name"].names):
            if record.nameID == identifier:
                font["name"].removeNames(nameID=identifier)
                break
        font["name"].setName(value, identifier, 3, 1, 0x409)


arabic = TTFont(sys.argv[2])
instantiateVariableFont(arabic, {"wght": 400, "wdth": 100}, inplace=True)
arabic.recalcTimestamp = False
rename(arabic, "Preview Arabic")
arabic.save(destination / "arabic.bin")

cjk = TTFont(sys.argv[1])
instantiateVariableFont(cjk, {"wght": 400}, inplace=True)
cjk.recalcTimestamp = False
static = BytesIO()
cjk.save(static)
static_bytes = static.getvalue()
pages = defaultdict(list)
for codepoint in cjk.getBestCmap():
    if codepoint >= 0x2E80:
        pages[codepoint >> 8].append(codepoint)

imports = ['import arabic from "./fallbacks/arabic.bin";']
entries = []
for page, characters in sorted(pages.items()):
    font = TTFont(BytesIO(static_bytes))
    font.recalcTimestamp = False
    options = subset.Options()
    options.layout_features = ["*"]
    options.drop_tables += ["DSIG", "meta", "vhea", "vmtx", "VORG"]
    options.hinting = False
    selected = subset.Subsetter(options=options)
    selected.populate(unicodes=characters)
    selected.subset(font)
    rename(font, f"Preview CJK {page:X}")
    name = f"cjk-{page:x}.bin"
    font.save(destination / name)
    imports.append(f'import page{page:x} from "./fallbacks/{name}";')
    entries.append(f"  [0x{page:x}, page{page:x}],")
    print(name, flush=True)

advances = {}
inter = TTFont("src/assets/inter.ttf.bin")
for codepoint, glyph in inter.getBestCmap().items():
    advances[codepoint] = inter["hmtx"][glyph][0] / inter["head"].unitsPerEm
for codepoint, glyph in arabic.getBestCmap().items():
    if 0x0600 <= codepoint <= 0x08FF or 0xFB50 <= codepoint <= 0xFDFF or 0xFE70 <= codepoint <= 0xFEFF:
        advances[codepoint] = arabic["hmtx"][glyph][0] / arabic["head"].unitsPerEm
for codepoint, glyph in cjk.getBestCmap().items():
    width = cjk["hmtx"][glyph][0] / cjk["head"].unitsPerEm
    if codepoint >= 0x2E80 and width != 1:
        advances[codepoint] = width
advance_entries = ",".join(f"[{codepoint},{width:.6f}]" for codepoint, width in sorted(advances.items()))

Path("src/assets/fallback-fonts.ts").write_text(
    "// Generated by scripts/subset-preview-fonts.py.\n" + "\n".join(imports) +
    "\n\nconst cjkPages = new Map<number, ArrayBuffer>([\n" + "\n".join(entries) + "\n]);\n" +
    f"\nconst advances = new Map<number, number>([{advance_entries}]);\n" +
    """
export function fallbackFontsForText(text: string): readonly ArrayBuffer[] {
  const fonts: ArrayBuffer[] = [];
  if (/[\\u0600-\\u08ff\\uFB50-\\uFDFF\\uFE70-\\uFEFF]/u.test(text)) fonts.push(arabic);
  const pages = new Set<number>();
  for (const character of text) {
    const codepoint = character.codePointAt(0)!;
    if (codepoint >= 0x2E80) pages.add(codepoint >>> 8);
  }
  for (const page of pages) {
    const font = cjkPages.get(page);
    if (font) fonts.push(font);
  }
  return fonts;
}

export function previewFontFamily(codepoint: number): string {
  if ((codepoint >= 0x0600 && codepoint <= 0x08FF) || (codepoint >= 0xFB50 && codepoint <= 0xFDFF)
    || (codepoint >= 0xFE70 && codepoint <= 0xFEFF)) return "Preview Arabic";
  const page = codepoint >>> 8;
  return cjkPages.has(page) ? `Preview CJK ${page.toString(16).toUpperCase()}` : "Inter";
}

export function previewAdvance(codepoint: number): number {
  return advances.get(codepoint) ?? 1;
}
""", encoding="utf-8")

# browser asset URLs and text metrics are derived from the same subset inventory.
subprocess.run(["node", "scripts/prepare-preview-fonts.ts"], check=True)
